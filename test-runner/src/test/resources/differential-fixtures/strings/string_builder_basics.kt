fun main() {
    val sb = StringBuilder()
    sb.append("hello")
    sb.append(' ')
    sb.append(42)
    sb.append(1.5)
    sb.append(true)
    println(sb.toString())
    println(sb.length)
    println(sb.isEmpty())
    println(sb)
    println("built: $sb")

    val chained = StringBuilder("start").append("-").append(1).appendLine().appendLine("next")
    println(chained.toString())
    println(chained.length)

    val cleared = StringBuilder("abc")
    cleared.clear()
    println(cleared.isEmpty())
    println(cleared.isNotEmpty())
    println(StringBuilder(10).append("x").toString())

    val joined = StringBuilder()
    println(sequenceOf(1, 2, 3).joinTo(joined).toString())
    println(sequenceOf(1, 2, 3).joinTo(StringBuilder(), separator = "|", prefix = "<", postfix = ">").toString())
    println(listOf("a", "b", "c").joinTo(StringBuilder(), "; ").toString())
    println(sequenceOf(1, 2, 3, 4, 5).joinTo(StringBuilder(), ",", limit = 3).toString())
    println(sequenceOf(1, 2, 3, 4, 5).joinTo(StringBuilder(), ",", limit = 3, truncated = "…").toString())
    println(sequenceOf(1, 2, 3).joinTo(StringBuilder(), "-") { "n$it" }.toString())
    println(setOf(7, 8).joinTo(StringBuilder(), "+").toString())
    var total = StringBuilder()
    for (i in 1..3) total.append(i).append(',')
    println(total)
}
