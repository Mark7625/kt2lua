data class P(val name: String, val age: Int)

fun main() {
    val xs = sequenceOf(3, 1, 4, 1, 5, 9, 2, 6)
    println(xs.sorted().toList())
    println(xs.sortedDescending().toList())
    println(xs.sortedBy { -it }.toList())
    println(xs.sortedByDescending { it % 3 }.toList())
    println(xs.sortedWith(compareBy { it % 4 }).toList())
    println(xs.sortedWith(compareByDescending { it }).first())
    println(generateSequence(1) { it + 1 }.take(5).sortedDescending().toList())

    println(xs.min())
    println(xs.max())
    println(xs.minOrNull())
    println(xs.maxOrNull())
    println(emptySequence<Int>().minOrNull())
    println(emptySequence<Int>().maxOrNull())

    val ps = sequenceOf(P("a", 30), P("b", 20), P("c", 30), P("d", 20))
    println(ps.minBy { it.age })
    println(ps.maxBy { it.age })
    println(ps.minByOrNull { it.age })
    println(ps.maxByOrNull { it.age })
    println(emptySequence<P>().maxByOrNull { it.age })
    println(ps.minOf { it.age })
    println(ps.maxOf { it.age })
    println(ps.minOfOrNull { it.age })
    println(ps.maxOfOrNull { it.age })
    println(emptySequence<P>().maxOfOrNull { it.age })
    println(ps.minWith(compareBy { it.name }))
    println(ps.maxWith(compareBy { it.name }))
    println(ps.minWithOrNull(compareBy { it.age }))
    println(ps.maxWithOrNull(compareBy { it.age }))
    println(ps.minOfWith(compareByDescending { it }) { it.age })
    println(ps.maxOfWith(compareByDescending { it }) { it.age })
    println(ps.minOfWithOrNull(compareBy { it }) { it.age })
    println(ps.maxOfWithOrNull(compareBy { it }) { it.age })

    println(xs.reduce { a, b -> a + b })
    println(xs.reduceOrNull { a, b -> a * b })
    println(emptySequence<Int>().reduceOrNull { a, b -> a + b })
    println(xs.reduceIndexed { i, a, b -> a + b * i })
    println(xs.reduceIndexedOrNull { i, a, b -> a - i * b })
    println(xs.foldIndexed(0) { i, acc, x -> acc + i * x })
    println(xs.average())
    println(emptySequence<Int>().average())
    println(xs.count { it > 3 })
    println(xs.sumOf { it * 2 })

    println(sequenceOf(7).single())
    println(sequenceOf(7).singleOrNull())
    println(sequenceOf(1, 2).singleOrNull())
    println(emptySequence<Int>().singleOrNull())
    println(xs.single { it == 9 })
    println(xs.singleOrNull { it == 1 })
    println(xs.singleOrNull { it == 100 })

    println(xs.elementAt(2))
    println(xs.elementAtOrNull(20))
    println(xs.elementAtOrElse(20) { -it })
    println(generateSequence(1) { it * 2 }.elementAt(10))
    println(xs.indexOf(4))
    println(xs.indexOf(100))
    println(xs.lastIndexOf(1))
    println(xs.indexOfFirst { it > 4 })
    println(xs.indexOfLast { it > 4 })
    println(generateSequence(1) { it + 1 }.indexOf(50))
    println(xs.contains(5))
    println(7 in xs)
    println(9 in xs)
    println(generateSequence(1) { it + 1 }.contains(30))

    println(xs.last())
    println(xs.lastOrNull())
    println(xs.last { it < 3 })
    println(xs.lastOrNull { it > 100 })
    println(xs.findLast { it % 2 == 0 })
    println(emptySequence<Int>().lastOrNull())

    println(sequenceOf(1 to "a", 2 to "b", 3 to "c").unzip())
    val (nums, letters) = sequenceOf(1 to "a", 2 to "b").unzip()
    println(nums)
    println(letters)

    println(xs.toSortedSet())
    println(xs.toHashSet().size)
    println(xs.toMutableSet().size)
    println(xs.toSet().size)

    println(xs.firstNotNullOf { if (it > 4) it * 2 else null })
    println(xs.firstNotNullOfOrNull { if (it > 40) it * 2 else null })

    println(xs.joinToString("-"))
    println(xs.joinToString(prefix = "<", postfix = ">"))
    println(xs.partition { it > 3 })
    println(xs.groupBy { it % 3 })
    println(xs.associate { it to it * it })
    println(xs.associateBy { it % 5 })
    println(xs.associateWith { it * 2 })
    var seen = ""
    xs.forEachIndexed { i, v -> seen = "$seen$i$v," }
    println(seen)

    val shuffled = xs.shuffled().toList()
    println(shuffled.size)
    println(shuffled.sorted() == xs.sorted().toList())

    val it1 = sequenceOf(1, 2, 3).iterator()
    var total = ""
    while (it1.hasNext()) total += it1.next()
    println(total)
    val it2 = iterator {
        yield(10)
        yield(20)
    }
    println(it2.next() + it2.next())
    println(it2.hasNext())

    var viaIterable = 0
    for (x in xs.asIterable()) viaIterable += x
    println(viaIterable)
    println(xs.asIterable().map { it * 2 })

    val dest = mutableListOf(0)
    xs.take(3).toCollection(dest)
    println(dest)
    val destSet = mutableSetOf(100)
    xs.toCollection(destSet)
    println(destSet.size)
}
