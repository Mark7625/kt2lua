data class P(val a: Int)

fun main() {
    val xs: Sequence<Int?> = sequenceOf(1, null, 3, null, 5)
    println(xs.toList())
    println(xs.filterNotNull().toList())
    println(xs.map { it ?: -1 }.toList())
    println(xs.mapNotNull { it?.let { v -> v * 2 } }.toList())
    println(xs.count { it == null })
    println(xs.filter { it != null }.toList())
    println(xs.map { if (it == null) null else it * 10 }.toList())
    println(xs.filterNotNull().sum())
    println(xs.withIndex().filter { it.value == null }.map { it.index }.toList())
    println(xs.indexOf(null))
    println(xs.contains(null))
    println(xs.first())
    println(xs.drop(1).first())
    println(xs.drop(1).firstOrNull())
    println(xs.distinct().toList())
    println(listOf(1, null, 2).asSequence().filterNotNull().toList())
    println(xs.plus(null).toList())
    println(xs.minus(null).toList())
    println(sequence { yield(1); yield(null); yield(3) }.toList())
    println(xs.sortedBy { it ?: 0 }.toList())
    println(xs.minOfOrNull { it ?: 0 })
    var nulls = 0
    xs.forEach { if (it == null) nulls += 1 }
    println(nulls)
    println(xs.any { it == null })
    println(xs.all { it != null })
    println(xs.find { it == null })
    println(xs.takeWhile { it != null }.toList())
    println(xs.fold(0) { acc, v -> acc + (v ?: 0) })

    println(sequenceOf(P(1), P(1), P(2)).distinct().toList())
    println(sequenceOf(P(1), P(1), P(2)).distinctBy { it }.toList())
    println(sequenceOf(P(1), P(2), P(3)).distinctBy { it.a % 2 }.toList())
    println(sequenceOf(P(5), P(5)).distinct().count())
}
