open class Animal(val name: String)
class Dog(val tag: String) : Animal(tag)
class Cat(val tag: String) : Animal(tag)

fun main() {
    val xs = sequenceOf(3, 1, 4, 1, 5, 9, 2, 6)

    val list1 = mutableListOf(100)
    println(xs.filterTo(list1) { it > 4 })
    println(xs.filterNotTo(mutableListOf<Int>()) { it > 4 })
    println(xs.filterIndexedTo(mutableListOf<Int>()) { i, v -> i % 2 == 0 })
    println(xs.mapTo(mutableListOf<String>()) { "n$it" })
    println(xs.mapIndexedTo(mutableListOf<Int>()) { i, v -> i * v })
    println(xs.mapNotNullTo(mutableListOf<Int>()) { if (it > 3) it * 2 else null })
    println(xs.mapIndexedNotNullTo(mutableListOf<Int>()) { i, v -> if (i > 5) v else null })
    println(xs.flatMapTo(mutableListOf<Int>()) { listOf(it, -it) }.take(6))
    println(xs.take(3).flatMapIndexedTo(mutableListOf<Int>()) { i, v -> listOf(i, v) })
    println(xs.filterNotNullTo(mutableListOf<Int>()))
    val set1 = mutableSetOf(1000)
    xs.filterTo(set1) { it % 2 == 1 }
    println(set1.size)
    println(xs.mapTo(mutableSetOf<Int>()) { it % 3 }.size)

    println(xs.groupByTo(mutableMapOf<Int, MutableList<Int>>()) { it % 3 })
    println(xs.groupByTo(mutableMapOf<Int, MutableList<String>>(), { it % 2 }, { "v$it" }))
    println(xs.associateTo(mutableMapOf<Int, Int>()) { it to it * it })
    println(xs.associateByTo(mutableMapOf<Int, Int>()) { it % 5 })
    println(xs.associateByTo(mutableMapOf<Int, String>(), { it % 4 }, { "x$it" }))
    println(xs.associateWithTo(mutableMapOf<Int, Int>()) { it * 2 })

    val mixed: Sequence<Any> = sequenceOf(1, "a", 2, "b", Dog("rex"), Cat("tom"), true)
    println(mixed.filterIsInstance<String>().toList())
    println(mixed.filterIsInstance<Int>().toList())
    println(mixed.filterIsInstance<Boolean>().toList())
    println(mixed.filterIsInstance<Animal>().map { it.name }.toList())
    println(mixed.filterIsInstance<Dog>().map { it.name }.toList())
    println(mixed.filterIsInstance<Cat>().map { it.name }.toList())
    println(listOf(1, "a", 2).filterIsInstance<Int>())
    println(mixed.filterIsInstanceTo<String, MutableList<String>>(mutableListOf()))
    println(generateSequence<Any>(1) { if (it is Int) "s$it" else null }.filterIsInstance<String>().toList())

    println(xs.groupingBy { it % 3 }.eachCount())
    println(listOf("a", "bb", "cc", "d").groupingBy { it.length }.eachCount())
    println(xs.groupingBy { it % 2 }.fold(0) { acc, v -> acc + v })
    println(xs.groupingBy { it % 2 }.fold(1) { acc, v -> acc * v })
    println(xs.groupingBy { it % 3 }.reduce { key, acc, v -> acc + v })
    println(xs.groupingBy { it % 3 }.aggregate { key, acc: Int?, v, first -> if (first) v else acc!! * v })
    println(sequenceOf("apple", "avocado", "banana").groupingBy { it.first() }.eachCount())
}
